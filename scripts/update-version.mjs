import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, '..');
const versionJsonPath = resolve(rootDir, 'version.json');
const webVersionTsPath = resolve(rootDir, 'apps/web/src/version.ts');

let currentVersion = '1.0.0';
try {
  const data = JSON.parse(readFileSync(versionJsonPath, 'utf8'));
  if (data && typeof data.version === 'string') {
    currentVersion = data.version.trim().replace(/^v/, '');
  }
} catch {
  // Fallback to 1.0.0
}

const tsContent = `// Auto-generated by scripts/bump-version.mjs or update-version.mjs
export const APP_VERSION = '${currentVersion}';
`;

let existing = '';
try {
  existing = readFileSync(webVersionTsPath, 'utf8');
} catch {
  // File may not exist yet
}

if (existing !== tsContent) {
  writeFileSync(webVersionTsPath, tsContent, 'utf8');
  console.log(`Synced APP_VERSION to ${currentVersion}`);
}
