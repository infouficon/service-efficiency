import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, '..');
const versionJsonPath = resolve(rootDir, 'version.json');
const webVersionTsPath = resolve(rootDir, 'apps/web/src/version.ts');

let currentVersion = '1.0.0';
try {
  const data = JSON.parse(readFileSync(versionJsonPath, 'utf8'));
  if (data && typeof data.version === 'string') {
    currentVersion = data.version.trim().replace(/^v/, '');
  }
} catch {
  // If version.json doesn't exist yet, start at 1.0.0
}

const parts = currentVersion.split('.').map((p) => parseInt(p, 10));
const major = Number.isFinite(parts[0]) ? parts[0] : 1;
const minor = Number.isFinite(parts[1]) ? parts[1] : 0;
const patch = Number.isFinite(parts[2]) ? parts[2] + 1 : 0;

const nextVersion = `${major}.${minor}.${patch}`;

// Write back to version.json
writeFileSync(versionJsonPath, JSON.stringify({ version: nextVersion }, null, 2) + '\n', 'utf8');

// Write to apps/web/src/version.ts
const tsContent = `// Auto-generated by scripts/bump-version.mjs or update-version.mjs
export const APP_VERSION = '${nextVersion}';
`;
writeFileSync(webVersionTsPath, tsContent, 'utf8');

console.log(`Bumped version: ${currentVersion} -> ${nextVersion}`);
